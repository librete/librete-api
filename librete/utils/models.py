from django.conf import settings
from django.contrib.auth import get_user_model
from django.db import models, router, transaction
from django.utils.translation import gettext_lazy as _


class TimestampModel(models.Model):
    created_at = models.DateTimeField(_("Created at"), auto_now_add=True)
    updated_at = models.DateTimeField(_("Updated at"), auto_now=True)

    class Meta:
        abstract = True


def lock_owner(user_id, using=None):
    """Lock the owner's user row until the end of the current transaction.

    Every write to an `OwnedModel` takes this lock first, so one user's writes are
    serialized: version checks (`If-Match`) can't race, and change-log rows are committed
    in the order of their ids, so a sync cursor never skips a change. A no-op on SQLite,
    which serializes all writes anyway.
    """
    user_model = get_user_model()
    queryset = user_model._base_manager.using(using).select_for_update()
    list(queryset.filter(pk=user_id).order_by().values_list("pk", flat=True))


class OwnedModel(TimestampModel):
    """Base for user-owned records. Reverse accessors are named after the app: `user.events`."""

    author = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        verbose_name=_("Author"),
        related_name="%(app_label)s",
        on_delete=models.CASCADE,
    )
    # Generated by the client for every create, so a retried POST returns the existing
    # record instead of creating a duplicate (see OwnedModelViewSet.create).
    client_id = models.UUIDField(_("Client ID"), null=True, blank=True, editable=False)
    # Incremented on every update (also from the admin); clients send it back in `If-Match`.
    version = models.PositiveIntegerField(_("Version"), default=1, editable=False)

    class Meta:
        abstract = True
        ordering = ["created_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["author", "client_id"],
                condition=models.Q(client_id__isnull=False),
                name="%(app_label)s_%(class)s_unique_client_id",
            ),
        ]

    def save(self, *args, **kwargs):
        using = kwargs.get("using") or router.db_for_write(type(self), instance=self)
        update_fields = kwargs.get("update_fields")
        with transaction.atomic(using=using):
            lock_owner(self.author_id, using)
            if not self._state.adding and (update_fields is None or update_fields):
                current = (
                    type(self)
                    ._base_manager.using(using)
                    .filter(pk=self.pk)
                    .values_list("version", flat=True)
                    .first()
                )
                self.version = (self.version if current is None else current) + 1
                if update_fields is not None:
                    kwargs["update_fields"] = {*update_fields, "version"}
            super().save(*args, **kwargs)
