from django.conf import settings
from django.db import models
from django.utils.translation import gettext_lazy as _


class TimestampModel(models.Model):
    created_at = models.DateTimeField(_("Created at"), auto_now_add=True)
    updated_at = models.DateTimeField(_("Updated at"), auto_now=True)

    class Meta:
        abstract = True


class OwnedModel(TimestampModel):
    """Base for user-owned records. Reverse accessors are named after the app: `user.events`."""

    author = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        verbose_name=_("Author"),
        related_name="%(app_label)s",
        on_delete=models.CASCADE,
    )
    # Generated by the client for every create, so a retried POST returns the existing
    # record instead of creating a duplicate (see OwnedModelViewSet.create).
    client_id = models.UUIDField(_("Client ID"), null=True, blank=True, editable=False)

    class Meta:
        abstract = True
        ordering = ["created_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["author", "client_id"],
                condition=models.Q(client_id__isnull=False),
                name="%(app_label)s_%(class)s_unique_client_id",
            ),
        ]
